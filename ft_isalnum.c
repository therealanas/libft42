int	ft_isalnum(int c)
{
	if ((c >= '0') && (c <= '9'))
		return (1);
	else if (((c <= 'z') && (c >= 'a')) || ((c <= 'Z') && (c >= 'A')))
		return (1);
	return (0);
}
