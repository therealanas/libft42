#include "libft.h"
#include <stddef.h>

t_list	*ft_lstlast(t_list *lst)
{
	if (lst == NULL)
		return (lst);
	while (lst->next != NULL)
	{
		lst = lst->next;
	}
	return (lst);
}

void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*last = ft_lstlast(*lst);

	if (last == NULL)
	{
		*lst = new;
		new->next = NULL;
	}
	else
	{
		last->next = new;
		new->next = NULL;
	}
}
